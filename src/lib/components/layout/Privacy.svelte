  개인정보처리방침


{siteConfig.siteName} 사이트(이하 {siteConfig.siteName})는 회원의 개인정보를 중요시하며, "정보통신망 이용촉진 및 정보보호 등에 관한 법률"을 준수하고 있습니다.
"{siteConfig.siteName}"는 개인정보처리방침을 통하여 회원이 제공하는 개인정보가 어떠한 용도와 방식으로 이용되고 있으며, 개인정보보호를 위해 어떠한 조치가 취해지고 있는지 알려드립니다.
"{siteConfig.siteName}"는 개인정보처리방침을 개정하는 경우 웹사이트 공지사항(또는 개별 공지)을 통하여 공지할 것입니다.
 
제1조 수집하는 개인정보 항목
"{siteConfig.siteName}"는 회원가입, 상담, 서비스 신청 등등을 위해 아래와 같은 개인정보를 수집하고 있습니다.
1. 회원 가입에서 아래 정보가 수집됩니다.
- 아이디, 비밀번호, 닉네임, 이메일, 전화번호
2. 사이트 내 접속 및 활동 시 아래 정보가 자동으로 생성되어 수집될 수 있습니다.
- 서비스 이용 기록, 접속 로그, 방문일시, 기기 정보, 쿠키, IP주소, 부정 이용 기록

 

제2조 개인정보의 수집 및 이용목적
"{siteConfig.siteName}"는 수집한 개인정보를 다음의 목적을 위해 활용합니다.
1. 서비스 제공에 관한 계약 이행 및 서비스 제공에 따른 요금정산 콘텐츠 제공
2. 회원제 서비스 이용에 따른 본인 확인, 개인 식별, 악성회원의 불량 이용 방지와 비인가 사용 방지, 가입 의사 확인, 각종 민원처리, 다중 계정 제한, 중복 가입 제한, 고지사항 전달
3. 마케팅 및 광고에 활용, 신규 서비스 개발 및 특화, 이벤트 등 광고성 정보 전달, 인구통계학적 특성에 따른 서비스 제공 및 광고 게재
4. 접속 빈도 파악 또는 회원의 서비스 이용에 대한 통계

 

제3조 개인정보의 보유 및 이용기간
"{siteConfig.siteName}"는 개인정보의 수집 및 이용목적이 달성된 후나 회원탈퇴와 같은 개인정보 수집 제공에 대한 동의 철회 시 해당 정보를 파기하는 등 필요한 조치를 취합니다.
다만 내부 방침 및 관계법령에 따라 보관할 수 있으며, 구체적인 개인정보의 보유 및 이용기간은 다음과 같습니다.
1. 불법적 사용자에 대한 관련 기관 수사 협조에 따라 개인정보가 최대 1년간 보관 후 파기됩니다.
2. 정리되지 않은 게시글 및 댓글은 장기 보관될 수 있습니다.
3. 논란 및 악성 이용자의 서비스 이용 제한과 재발 방지를 위해 회원의 DI값(중복가입 확인 정보), 서비스 이용 제한 조치 이력을 5년간 보관합니다.
4. 전자상거래 등에서의 소비자 보호에 관한 법률, 통신비밀보호법 등 법령에 의해 보관해야 하는 정보는 법령이 정한 기간 동안 보관합니다.

 

제4조 개인정보의 파기절차 및 방법
"{siteConfig.siteName}"는 원칙적으로 개인정보 수집 및 이용목적이 달성된 후에는 해당 정보를 지체 없이 파기합니다. 파기절차 및 방법은 다음과 같습니다.
1. 파기절차
① 회원님이 회원가입 등을 위해 입력하신 정보는 목적이 달성된 후 별도의 DB로 옮겨져(종이의 경우 별도의 서류함) 내부 방침 및 기타 관련 법령에 의한 정보보호 사유에 따라(보유 및 이용기간 참조) 일정 기간 저장된 후 파기됩니다.
② 별도 DB로 옮겨진 개인정보는 법률에 의한 경우가 아니고서는 보유되는 이외의 다른 목적으로 이용되지 않습니다.
2. 파기방법
- 전자적 파일 형태로 저장된 개인정보는 기록을 재생할 수 없는 기술적 방법을 사용하여 삭제합니다.

 

제5조 개인정보 제공
"{siteConfig.siteName}"는 회원의 개인정보를 원칙적으로 외부에 제공하지 않습니다. 다만, 아래의 경우에는 예외로 합니다.
1. 회원들이 사전에 동의한 경우
2. 법령의 규정에 의거하거나, 수사 목적으로 법령에 정해진 절차와 방법에 따라 수사기관의 요구가 있는 경우 (사이버안전국이나 경찰서에서 요청한 경우)

 

제6조 수집한 개인정보의 위탁
"{siteConfig.siteName}"는 회원의 동의 없이 회원의 정보를 외부 업체에 위탁하지 않습니다.
향후 그러한 필요가 생길 경우, 위탁 대상자와 위탁 업무 내용에 대해 회원에게 통지하고 필요한 경우 사전 동의를 받도록 하겠습니다.

 

제7조 회원 및 법정대리인의 권리와 그 행사방법
1. 회원 및 법정 대리인은 언제든지 등록되어 있는 자신 혹은 당해 만 14세 미만 아동의 개인정보를 조회하거나 수정할 수 있으며 가입 해지를 요청할 수도 있습니다.
2. 회원 혹은 만 14세 미만 아동의 개인정보 조회 및 수정을 위해서는 ‘개인정보 변경’(또는 ‘회원정보 수정’ 등)을 가입 해지(동의 철회)를 위해서는 “회원탈퇴”를 클릭하여 본인 확인 절차를 거치신 후 직접 열람, 정정 또는 탈퇴가 가능합니다. 혹은 개인정보관리책임자에게 이메일로 연락하시면 지체 없이 조치하겠습니다.
3. 회원 개인정보의 오류에 대한 정정을 요청하신 경우에는 정정을 완료하기 전까지 당해 개인정보를 이용 또는 제공하지 않습니다. 또한 잘못된 개인정보를 제3자에게 이미 제공한 경우에는 정정 처리결과를 제3자에게 지체 없이 통지하여 정정이 이루어지도록 하겠습니다.
4. "{siteConfig.siteName}"는 회원 혹은 법정 대리인의 요청에 의해 해지 또는 삭제된 개인정보는“"{siteConfig.siteName}"이 수집하는 개인정보의 보유 및 이용기간”에 명시된 바에 따라 처리하고 그 외의 용도로 열람 또는 이용할 수 없도록 처리하고 있습니다.

 

제8조 개인정보 자동수집 장치의 설치, 운영 및 그 거부에 관한 사항
"{siteConfig.siteName}"는 회원의 정보를 수시로 저장하고 찾아내는 ‘쿠키(cookie)’ 등을 운용합니다.
쿠키는 웹사이트를 운영하는데 이용되는 서버가 회원의 브라우저에 보내는 작은 정보이며 회원의 컴퓨터 하드디스크 및 보조기억장치에 저장되기도 합니다. "{siteConfig.siteName}"는 다음과 같은 목적을 위해 쿠키를 사용합니다.
1. 쿠키 등 사용 목적
- 회원과 비회원의 접속 빈도나 방문 시간 등을 분석, 회원의 취향과 관심분야를 파악 및 자취 추적, 각종 이벤트 참여 정도 및 방문 횟수 파악 등을 통한 타겟 마케팅 및 개인 맞춤 서비스 제공
2. 쿠키의 설치 및 운영 거부
- 회원은 웹 브라우저 상단의 도구 > 인터넷 옵션 > 개인정보 메뉴의 설정을 통해 쿠키를 거부할 수 있습니다.
3. 쿠키 설치를 거부할 경우 일부 서비스 이용에 어려움이 발생할 수 있습니다.

 

